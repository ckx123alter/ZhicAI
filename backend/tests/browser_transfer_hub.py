"""Transfer tab, payee management and real receipts on an isolated demo ledger."""
from pathlib import Path
import argparse
from playwright.sync_api import sync_playwright,expect

parser=argparse.ArgumentParser()
parser.add_argument('--url',required=True)
base=parser.parse_args().url
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1080},reduced_motion='reduce')
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    from backend.tests.browser_auth import login
    login(page,base)
    page.goto(base,wait_until='networkidle')
    expect(page.get_by_role('tab')).to_have_text(['首页','账单','理财','转账','我的'])
    page.get_by_role('tab',name='转账',exact=True).click()
    expect(page.get_by_role('heading',name='转账',exact=True)).to_be_visible()
    expect(page.locator('.transfer-shortcuts button')).to_have_text(['银行账号转账','转账记录','常用收款人'])
    expect(page.get_by_role('heading',name='最近转账对象',exact=True)).to_be_visible()
    before=page.request.get(base+'/api/account-state').json()['balance']
    page.get_by_role('button',name='银行账号转账',exact=True).click()
    expect(page.get_by_role('heading',name='银行账号转账',exact=True)).to_be_visible()
    page.get_by_role('button',name='返回转账',exact=True).click()
    page.get_by_role('button',name='常用收款人',exact=True).click()
    page.get_by_role('button',name='新增常用收款人',exact=True).click()
    page.locator('input[name="holder_name"]').fill('陈某（演示）')
    page.locator('input[name="bank_name"]').fill('演示银行')
    page.locator('input[name="account_number"]').fill('0000000000002789')
    page.locator('input[name="nickname"]').fill('阿姨')
    page.get_by_role('button',name='保存',exact=True).click()
    page.get_by_role('textbox',name='搜索收款人').fill('2789')
    page.locator('.saved-payee-row .payee-select').click()
    expect(page.get_by_role('heading',name='确认转账',exact=True)).to_be_visible()
    expect(page.locator('.transfer-recipient-summary')).to_contain_text('阿姨')
    expect(page.locator('.transfer-recipient-summary')).to_contain_text('2789')
    expect(page.locator('.recipient-first-transfer')).to_have_count(0)
    page.locator('.modal-sheet input').fill('123.45')
    page.get_by_role('button',name='确认',exact=True).click()
    expect(page.locator('.modal-sheet')).not_to_be_visible()
    expect(page.locator('.recent-payee-row').filter(has_text='阿姨')).to_contain_text('123.45')
    expect(page.locator('.recent-payee-row').filter(has_text='阿姨').locator('.payee-row-copy small').first).to_have_text('常用联系人')
    assert page.request.get(base+'/api/account-state').json()['balance']==round(before-123.45,2)
    out=Path('.test-runs');out.mkdir(exist_ok=True)
    page.locator('.phone').screenshot(path=str(out/'transfer-home.png'))
    page.get_by_role('button',name='转账记录',exact=True).click()
    expect(page.locator('.transfer-record').filter(has_text='阿姨')).to_contain_text('2789')
    page.reload(wait_until='networkidle')
    expect(page.locator('.transfer-record').filter(has_text='阿姨')).to_contain_text('123.45')
    page.get_by_role('button',name='返回转账',exact=True).click()
    page.set_viewport_size({'width':390,'height':844})
    expect(page.locator('.recent-payee-row').filter(has_text='阿姨')).to_be_visible()
    assert page.locator('.transfer-page').evaluate('(el)=>el.scrollWidth<=el.clientWidth+1')
    page.screenshot(path=str(out/'transfer-mobile.png'),full_page=True)
    page.get_by_role('button',name='常用收款人',exact=True).click()
    page.get_by_role('button',name='编辑阿姨',exact=True).click()
    page.locator('input[name="account_number"]').fill('0000000000002790')
    page.get_by_role('button',name='保存',exact=True).click()
    page.get_by_role('button',name='返回转账',exact=True).click()
    expect(page.locator('.recent-payee-row').filter(has_text='阿姨')).to_contain_text('收款资料已更新')
    page.locator('.recent-payee-row').filter(has_text='阿姨').click()
    expect(page.locator('.transfer-recipient-summary')).to_contain_text('2790')
    expect(page.locator('.modal-sheet input')).to_have_value('')
    page.get_by_role('button',name='关闭',exact=True).click()
    page.get_by_role('button',name='常用收款人',exact=True).click()
    page.get_by_role('button',name='编辑阿姨',exact=True).click()
    page.get_by_role('button',name='移除收款人',exact=True).click()
    page.get_by_role('button',name='确认移除',exact=True).click()
    expect(page.locator('.saved-payee-row').filter(has_text='阿姨')).to_have_count(0)
    page.get_by_role('button',name='返回转账',exact=True).click()
    expect(page.locator('.recent-payee-row').filter(has_text='阿姨').locator('.payee-row-copy small').first).to_have_text('非常用联系人')
    page.get_by_role('tab',name='首页',exact=True).click()
    page.locator('.composer input').fill('给陌生人转50元')
    page.get_by_role('button',name='发送',exact=True).click()
    expect(page.locator('.message.agent').last).to_contain_text('先添加')
    page.get_by_role('button',name='新增常用收款人',exact=True).click()
    expect(page.get_by_role('heading',name='新增常用收款人',exact=True)).to_be_visible()
    expect(page.locator('input[name="nickname"]')).to_have_value('陌生人')
    page.locator('input[name="holder_name"]').fill('新收款人（演示）')
    page.locator('input[name="bank_name"]').fill('演示银行')
    page.locator('input[name="account_number"]').fill('0000000000009999')
    page.get_by_role('button',name='保存',exact=True).click()
    expect(page.get_by_role('heading',name='确认转账',exact=True)).to_be_visible()
    expect(page.locator('.modal-sheet input')).to_have_value('50')
    assert page.request.get(base+'/api/account-state').json()['balance']==round(before-123.45,2)
    assert not errors,errors
    browser.close()
    print('PASS: five-tab layout, payee CRUD, bound transfer, persisted receipt/recent people, mobile layout, unknown-payee add-and-confirm flow')
